
    create table company (
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) not null,
        kode varchar(30) not null unique,
        nama varchar(150) not null,
        nama_grup varchar(150),
        logo_url varchar(500),
        primary key (id)
    );

    create table divisi (
        aktif boolean not null,
        company_id bigint not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) not null,
        kode varchar(30) not null unique,
        nama varchar(150) not null,
        primary key (id)
    );

    create table mata_anggaran (
        aktif boolean not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) not null,
        tipe varchar(10) not null check (tipe in ('OPEX','CAPEX')),
        no_coa varchar(30) not null unique,
        kategori varchar(100),
        nama varchar(200) not null,
        primary key (id)
    );

    create table milestone_pekerjaan (
        tanggal_mulai date,
        tanggal_selesai date not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        pekerjaan_id bigint not null,
        updated_at timestamp(6) not null,
        status varchar(15) not null check (status in ('BELUM_MULAI','BERJALAN','SELESAI')),
        nama varchar(200) not null,
        catatan varchar(1000),
        primary key (id)
    );

    create table pekerjaan (
        anggaran numeric(19,2) not null,
        estimasi_selesai date,
        progress integer not null,
        tahun integer not null,
        tanggal_mulai date,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        program_kerja_id bigint not null,
        updated_at timestamp(6) not null,
        tipe varchar(10) not null check (tipe in ('OPEX','CAPEX')),
        jenis_periode varchar(15) not null check (jenis_periode in ('SINGLE_YEAR','MULTI_YEAR')),
        pic varchar(100) not null,
        nama varchar(200) not null,
        deskripsi varchar(2000),
        tindak_lanjut varchar(2000),
        primary key (id)
    );

    create table program_kerja (
        pagu numeric(19,2),
        planning_budget numeric(19,2) not null,
        tahun integer not null,
        created_at timestamp(6) not null,
        divisi_id bigint not null,
        id bigint generated by default as identity,
        mata_anggaran_id bigint not null,
        updated_at timestamp(6) not null,
        status varchar(10) not null check (status in ('OPEN','CLOSED')),
        tipe varchar(10) not null check (tipe in ('OPEX','CAPEX')),
        keterangan varchar(1000),
        primary key (id),
        constraint uk_program_divisi_tahun_coa unique (divisi_id, tahun, mata_anggaran_id)
    );

    create table progress_pekerjaan (
        persen integer not null,
        tanggal date not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        pekerjaan_id bigint not null,
        updated_at timestamp(6) not null,
        dilaporkan_oleh varchar(100),
        catatan varchar(2000),
        tindak_lanjut varchar(2000),
        primary key (id)
    );

    create table realisasi (
        nilai numeric(19,2) not null,
        periode_bulan integer not null,
        periode_tahun integer not null,
        tanggal date not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        pekerjaan_id bigint not null,
        updated_at timestamp(6) not null,
        no_dokumen varchar(100),
        keterangan varchar(1000),
        primary key (id)
    );

