-- Migrasi untuk database PostgreSQL yang sudah berjalan (v3): tabel user hasil login LDAP + sesi token.
-- Idempoten, aman dijalankan ulang. Database baru cukup memakai db/schema.sql.

create table if not exists app_user (
    aktif boolean not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    last_login_at timestamp(6),
    updated_at timestamp(6) not null,
    sumber varchar(10) not null check (sumber in ('LDAP','DEV')),
    username varchar(100) not null unique,
    departemen varchar(200),
    email varchar(200),
    jabatan varchar(200),
    nama varchar(200),
    user_principal_name varchar(200),
    distinguished_name varchar(500),
    primary key (id)
);

create table if not exists user_session (
    created_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    user_id bigint not null references app_user,
    ip_address varchar(64),
    token_hash varchar(64) not null unique,
    primary key (id)
);
