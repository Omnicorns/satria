-- Migrasi untuk database PostgreSQL yang sudah menjalankan v4 (login LDAP): departemen AD + relasi user.
-- Idempoten, aman dijalankan ulang. Database baru cukup memakai db/schema.sql.

create table if not exists ldap_departemen (
    created_at timestamp(6) not null,
    divisi_id bigint references divisi,
    id bigint generated by default as identity,
    last_sync_at timestamp(6),
    updated_at timestamp(6) not null,
    nama varchar(200) not null unique,
    primary key (id)
);

alter table app_user add column if not exists ldap_departemen_id bigint references ldap_departemen;
alter table app_user add column if not exists last_sync_at timestamp(6);
